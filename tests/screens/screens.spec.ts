import { expect, test } from '@playwright/test'
import { addProject, launch, makeSandbox, newItem } from '../e2e/helpers'

test('screens', async () => {
  const sb = makeSandbox()
  const { app, page } = await launch(sb)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 860))
  await addProject(app, page, sb.repoA)
  await addProject(app, page, sb.repoB)
  await page.locator('.pj').first().click()
  for (const [t, d, p, s] of [['Export and import JSON', 'Header buttons: download all data to a file and load it back.', 'high', 'progress'], ['Recurring events', 'Daily / weekdays / weekly.', 'med', 'open'], ['Search notes', '', 'med', 'open'], ['Tasks with start/end', '', 'high', 'done']]) {
    await newItem(page, 'task'); await page.fill('#tTitle', t); await page.fill('#tDesc', d)
    await page.click(`[data-seg="prio"] [data-val="${p}"]`); await page.click(`[data-seg="status"] [data-val="${s}"]`)
  }
  await page.locator('.ti').first().click()
  await page.screenshot({ path: 'test-results/shots/1-tasks.png' })
  await page.click('[data-tab="notes"]')
  await newItem(page, 'note'); await page.fill('#nTitle', 'Google OAuth')
  await page.fill('#nDesc', 'Needs the `calendar.readonly` scope.\n\n> In *Testing* mode the refresh token lasts **7 days**.\n\n- [x] Create the OAuth client\n- [ ] Switch the app to Production\n\n## Links\nDocs: [Google Calendar API](https://developers.google.com/calendar)')
  await page.keyboard.press('Escape')
  await page.screenshot({ path: 'test-results/shots/2-notes.png' })
  await page.click('#newFork'); await page.fill('#fName', 'Export JSON')
  await page.screenshot({ path: 'test-results/shots/3-fork-modal.png' })
  await page.click('.modal .btn.pri')
  await page.click('[data-pick="task"]'); await page.click('.pop [data-att]')
  await page.click('[data-pick="note"]'); await page.click('.pop [data-att]')
  await page.press('#prompt', 'Enter')
  await expect(page.locator('.msg:not(.me) .body')).toContainText('Done.')
  await page.screenshot({ path: 'test-results/shots/4-chat.png' })
  await page.click('[data-v="changes"]'); await page.click('[data-change="README.md"]')
  await page.screenshot({ path: 'test-results/shots/5-changes.png' })
  await page.click('[data-v="files"]'); await page.click('[data-dir="src"]'); await page.click('[data-file="src/app.ts"]')
  await page.locator('.cm-line').nth(3).click(); await page.keyboard.press('End'); await page.keyboard.type(' // edited by hand')
  await page.waitForTimeout(600)
  await page.screenshot({ path: 'test-results/shots/6-explorer.png' })
  await page.click('[data-v="term"]'); await page.click('.xhost'); await page.keyboard.type('git status --short && ls\n'); await page.waitForTimeout(800)
  await page.screenshot({ path: 'test-results/shots/7-terminal.png' })
  await page.click('[data-v="git"]'); await page.click('#gCommit')
  await page.fill('#cMsg', 'Add JSON export and import')
  await page.screenshot({ path: 'test-results/shots/8-commit.png' })
  await page.click('.modal .btn.pri'); await page.locator('.fi.cmt').first().click()
  await page.screenshot({ path: 'test-results/shots/9-git.png' })
  await page.click('#accBtn')
  await page.screenshot({ path: 'test-results/shots/11-account.png' })
  await page.keyboard.press('Escape'); await page.click('#openSettings')
  await page.screenshot({ path: 'test-results/shots/12-settings.png' })
  await app.close()
})
