import { expect, test } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
import { addProject, launch, makeSandbox } from './helpers'

test('accounts: detected folders, default, per-project account used by agents, sign in, remove', async () => {
  const sb = makeSandbox()
  let { app, page } = await launch(sb)
  await addProject(app, page, sb.repoA)
  await addProject(app, page, sb.repoB)

  await page.click('#openSettings')
  const personal = page.locator('[data-account="dir:personal"]')
  const work = page.locator('[data-account="dir:work"]')
  await expect(personal).toContainText('Claude · personal')
  await expect(personal).toContainText('personal@example.com')
  await expect(personal).toContainText('Signed in')
  await expect(personal.locator('.pill.def')).toHaveText('Default')
  await expect(personal).toContainText('used by easy-calendar, shop-api')
  await expect(work).toContainText(path.join(sb.home, '.claude-work'))
  await work.locator('[data-default]').click()
  await expect(work.locator('.pill.def')).toHaveText('Default')
  await page.keyboard.press('Escape')
  await expect(page.locator('#accBtn')).toContainText('work')

  // pin easy-calendar to personal, shop-api keeps the default (work)
  await page.locator('.pj').first().click()
  await page.click('#accBtn')
  await expect(page.locator('[data-acc=""]')).toContainText('Default · Claude · work')
  await page.click('[data-acc="dir:personal"]')
  await expect(page.locator('#accBtn')).toContainText('personal')

  const runAgent = async () => {
    await page.click('#newFork')
    await page.click('.modal .btn.pri')
    await page.fill('#prompt', 'hello')
    await page.press('#prompt', 'Enter')
    await expect(page.locator('.msg:not(.me) .body')).toContainText('Done.')
  }
  await runAgent()
  await page.locator('.pj').nth(1).click()
  await expect(page.locator('#accBtn')).toContainText('work')
  await runAgent()
  const calls = sb.readLog().filter((c) => c.mode === 'agent')
  expect(calls.map((c) => c.config)).toEqual([path.join(sb.home, '.claude-personal'), path.join(sb.home, '.claude-work')])

  // add an account: new config folder + sign-in terminal running the CLI
  await page.click('#openSettings')
  await page.click('#aNew')
  await page.fill('#aLabel', 'Client Acme')
  await page.click('#aAdd')
  await expect(page.locator('.loginbox')).toBeVisible()
  await expect(page.locator('.loginbox .xterm-rows')).toContainText('Type /login')
  await page.click('.loginbox .xhost')
  await page.keyboard.type('/login\r')
  await expect(page.locator('.loginbox .xterm-rows')).toContainText('Logged in as new@example.com')
  await page.click('#loginDone')
  const acme = page.locator('[data-account="dir:client-acme"]')
  await expect(acme).toContainText('Signed in')
  await expect(acme).toContainText('new@example.com')
  expect(fs.existsSync(path.join(sb.home, '.claude-client-acme', '.claude.json'))).toBe(true)
  await acme.locator('[data-remove]').click()
  await page.click('.modal .btn.danger')
  await expect(acme).toHaveCount(0)
  await page.keyboard.press('Escape')

  // survives restart
  await app.close()
  ;({ app, page } = await launch(sb))
  await page.locator('.pj').first().click()
  await expect(page.locator('#accBtn')).toContainText('personal')
  await page.click('#openSettings')
  await expect(page.locator('[data-account="dir:work"] .pill.def')).toHaveText('Default')
  await app.close()
})

test('appearance and editor settings apply live and persist', async () => {
  const sb = makeSandbox()
  let { app, page } = await launch(sb)
  await addProject(app, page, sb.repoA)
  await page.click('#openSettings')
  await page.click('[data-sec="appearance"]')
  await page.click('[data-accent="Green"]')
  await page.click('[data-radius="6"]')
  await page.selectOption('[data-sel="uiSize"]', '15')
  const cssVar = (n: string) => page.evaluate((v) => document.documentElement.style.getPropertyValue(v), n)
  expect(await cssVar('--accent')).toBe('#10b981')
  expect(await cssVar('--r')).toBe('6px')
  expect(await cssVar('--ui-fs')).toBe('15px')
  await page.click('[data-sec="editor"]')
  await page.click('[data-tog="lineNumbers"]')
  await expect(page.locator('body')).toHaveClass(/no-ln/)
  await page.click('[data-sec="terminal"]')
  await page.selectOption('[data-sel="shell"]', 'bash')
  await page.keyboard.press('Escape')
  await app.close()
  ;({ app, page } = await launch(sb))
  expect(await cssVar('--accent')).toBe('#10b981')
  await expect(page.locator('body')).toHaveClass(/no-ln/)
  await page.click('#openSettings')
  await page.click('[data-sec="terminal"]')
  await expect(page.locator('[data-sel="shell"]')).toHaveValue('bash')
  await page.click('#sReset')
  await page.click('.modal .btn.danger')
  await expect.poll(() => cssVar('--accent')).toBe('#3b82f6')
  await expect(page.locator('body')).not.toHaveClass(/no-ln/)
  await app.close()
})

test('assistant: bottom-left, creates tasks and notes, opens them, menu shortcut', async () => {
  const sb = makeSandbox()
  const { app, page } = await launch(sb)
  await addProject(app, page, sb.repoA)
  await expect(page.locator('#helper')).toHaveCount(0)
  const btn = (await page.locator('#openHelper').boundingBox())!
  const win = page.viewportSize() ?? (await page.evaluate(() => ({ width: innerWidth, height: innerHeight })))
  expect(btn.x).toBeLessThan(60)
  expect(btn.y).toBeGreaterThan(win.height - 80)
  await page.click('#openHelper')
  const panel = (await page.locator('#helper').boundingBox())!
  expect(panel.x).toBeLessThan(80)
  await expect(page.locator('#helper header')).toContainText('easy-calendar · Claude · personal')

  await page.fill('#helperIn', 'Create task fix week start on Monday, urgent')
  await page.press('#helperIn', 'Enter')
  await expect(page.locator('.hm .tool').last()).toHaveText('create_task(title: "Fix week start on Monday", priority: high)')
  await expect(page.locator('.ti b')).toHaveText(['Fix week start on Monday'])
  await expect(page.locator('.ti .prio')).toHaveText(['High'])
  await page.fill('#helperIn', 'Note: Supabase — keep refresh tokens server-side')
  await page.press('#helperIn', 'Enter')
  await expect(page.locator('.hm .tool').last()).toHaveText('create_note(title: "Supabase")')
  await page.locator('[data-hopen^="note"]').click()
  await expect(page.locator('[data-tab="notes"]')).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#nTitle')).toHaveValue('Supabase')
  await page.fill('#helperIn', 'What is open?')
  await page.press('#helperIn', 'Enter')
  await expect(page.locator('.hm').last()).toContainText('1 open: Fix week start on Monday')
  const call = sb.readLog().find((c) => c.mode === 'assistant')
  expect(call).toMatchObject({ config: path.join(sb.home, '.claude-personal'), model: 'haiku', tools: '' })

  // close; View → Assistant (⌘J) opens it again with history
  await page.click('#helperClose')
  await expect(page.locator('#helper')).toHaveCount(0)
  await app.evaluate(({ Menu }) => {
    const find = (items: Electron.MenuItem[]): Electron.MenuItem | undefined => {
      for (const i of items) { if (i.label === 'Assistant') return i; const s = i.submenu && find(i.submenu.items); if (s) return s }
    }
    find(Menu.getApplicationMenu()!.items)!.click()
  })
  await expect(page.locator('#helper .hm')).toHaveCount(6)
  await app.close()
})
